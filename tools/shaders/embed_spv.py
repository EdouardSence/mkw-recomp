"""Compile a runtime compute shader (runtime/shaders/X.comp) into runtime/gfx/vk/spv/X_spv.h as a uint32 array.

Usage: uv run tools/shaders/embed_spv.py runtime/shaders/bc7_encode.comp
"""

import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main() -> None:
    src = Path(sys.argv[1]).resolve()
    name = src.stem
    with tempfile.TemporaryDirectory() as d:
        spv = Path(d, f"{name}.spv")
        subprocess.run(["glslc", "--target-env=vulkan1.3", "-O", str(src), "-o", str(spv)], check=True)
        data = spv.read_bytes()
    words = [int.from_bytes(data[i : i + 4], "little") for i in range(0, len(data), 4)]
    rows = [", ".join(f"0x{w:08x}" for w in words[i : i + 8]) for i in range(0, len(words), 8)]
    out = ROOT / "runtime/gfx/vk/spv" / f"{name}_spv.h"
    rel = src.relative_to(ROOT)
    sha = hashlib.sha256(src.read_bytes()).hexdigest()
    body = ",\n    ".join(rows)
    out.write_text(
        f"// Generated by tools/shaders/embed_spv.py from {rel}; do not edit.\n// source sha256 {sha}\n"
        f"#pragma once\n#include <stdint.h>\nstatic const uint32_t {name}_spv[] = {{\n    {body}\n}};\n"
    )
    print(f"{out.relative_to(ROOT)}: {len(words)} words")


if __name__ == "__main__":
    main()
